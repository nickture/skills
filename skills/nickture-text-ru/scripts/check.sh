#!/usr/bin/env bash
# Механический поиск по правилу «Сначала механически, потом глазами».
# Запуск из любой папки: bash <папка скилла>/scripts/check.sh ФАЙЛ…
# Вместо файла можно передать «-» и подать текст на вход.
# Строка вывода: правило | файл:строка:найденное. Совпадение ещё не нарушение,
# каждое сверяется с правилом, названным в начале строки.

# Цитаты в ёлочках, код, HTML-теги, адреса ссылок, номера ГОСТов и строки «Плохо» убираются, номера строк сохраняются.
# В строках «> Хорошо:» ёлочки остаются: хороший пример учит так же, как правило, и проверяется вместе с текстом.
# Хвост «законно …» в них убирается, потому что там перечислены законные случаи, похожие на нарушение.
strip() {
  awk '/^ *```/ { f = !f; print ""; next } { print f ? "" : $0 }' "$1" |
    sed -E 's/^( *> Хорошо:.*)законн.*$/\1/; /^ *> Хорошо:/!s/«[^»]*»//g; s/`[^`]*`//g; s/<[^>]+>//g; s/\]\([^)]*\)//g; s/ГОСТ [0-9.]+-[0-9]+//g; s/„[^“]*“//g; s/^( *> Плохо:).*/\1/'
}

# hit ПРАВИЛО ШАБЛОН [i] — ищет шаблон в очищенном тексте, i включает поиск без учёта регистра
hit() { grep -no${3:-}E -- "$2" "$T" | sed "s#^#$1 | $name:#"; }

ADJ='настоящ|следующ|предыдущ|будущ|текущ|общ|недостающ|подходящ|соответствующ'

for f in "$@"; do
  name=$f
  T=$(mktemp)
  strip "$f" > "$T"

  # одно «не X, а Y» на каждые полные 750 слов, в тексте короче одно
  w=$(wc -w < "$T"); n=$(grep -oiE '(^|[ «(])не [^,.:;!?]{1,60}, а |, а не ' "$T" | wc -l | tr -d ' ')
  [ "$n" -gt 0 ] && echo "«Не X, а Y» | $name: лимит $(( w / 750 > 0 ? w / 750 : 1 )), найдено $n"
  hit '«Не X, а Y»' '(^|[ «(])не [^,.:;!?]{1,60}, а |, а не |(^|[.!?] )это не [^,.]{1,40}, это ' i
  # та же пара через тире («Сервис не хранит файлы — он отдаёт ссылку»), поиск находит и законные фразы
  hit '«Не X, а Y»' '(^|[ «(])не [^.,–—]{1,40} [–—] [а-яё]+' i
  # в прямом смысле слово законно, таблица в файле «Слоп: стоп-слова»
  hit 'Слоп: стоп-слова' '(держит|держится|живёт|живут|несёт|несут|спорит| уходит|упирается|хорон|убива|съеда|цепляет|тих[аиоуеыя]|раньше|жд[её]т|ждут|спеш|поверх[ .,:;]|сто(ит|ят)[ .,:;])' i
  hit 'Действие названо существительным' '(^|[^а-яё])(осуществл|производит(ся)?[ ,.]|имеет место|носит [а-яё]+ характер)' i
  hit 'Канцелярское служебное слово' '(^|[^а-яё])(данн(ый|ая|ое|ого|ому|ом)|указанн(ый|ая|ое)|в целях|в случае если|при наличии|не представляется возможным)' i
  hit 'Цепочка родительных падежей' '[а-яё]+(ения|ания|ации) +[а-яё]+(ения|ания|ации|ов|ий) +[а-яё]+(ения|ания|ации|ов|ий)' i
  # два причастия в одном предложении, кроме прилагательных, похожих на причастия
  hit 'Причастный оборот вместо придаточного' '[а-яё]+(ущ|ющ|ащ|ящ|вш|ем|им)(ий|ая|ее|ие|его|ей|их)[^.!?…]*[а-яё]+(ущ|ющ|ащ|ящ|вш|ем|им)(ий|ая|ее|ие|его|ей|их)' | grep -viE "$ADJ"
  # «всё просто» в значении «несложно» законно
  hit 'Усилитель' '(^|[^а-яё])(просто|вообще|вовсе|действительно|на самом деле|реально|ровно (то|тот|та|те|так|это|этот)|именно то|как раз то)([^а-яё]|$)' i
  # «без» с оценкой, ощущением или чужим инструментом
  hit '«Без» вместо факта' '(^|[^а-яё])без (лишн|ненужн|жёстк|жестк|уловок|хлопот|головной боли|догад|рутин|суеты|усилий|сторонн)' i
  # «разом» в значении «одновременно», «раз за разом» законно
  sed -E 's/[Рр]аз за разом//g' "$T" | grep -noiE '(^|[^а-яё])разом([^а-яё]|$)' | sed "s#^#Язык деловой, без разговорного | $name:#"
  # «поэтому» собрано из «по этому», и пара с «это» звучит повтором
  hit 'Однокоренные слова не стоят рядом' '(^|[^а-яё])(поэтому эт|эт(о|а|и|от|у)( [а-яё]+){0,2},? поэтому)' i
  # глагол во множественном числе без подлежащего после местоимения: «его меняют».
  # Подлежащее после глагола («её задают паддинг») тоже находится, и такое предложение перестраивается
  hit 'Обобщение вместо участника' '(^|[^а-яё])(его|её|их) [а-яё]+(ют|ят)([^а-яё]|$)' i
  # два предложения по одному-три слова подряд; один отрезанный хвост считается по «Парцелляции»
  hit 'Рубленые фразы' '(^|[.!?] |«|\*\* )[А-ЯЁA-Z][а-яёa-z-]*(,? [а-яёa-z-]+){0,2}[.!?] [А-ЯЁA-Z][а-яёa-z-]*(,? [а-яёa-z-]+){0,2}[.!?]'
  # короткая фраза в конце абзаца, одна на 750 слов
  hit 'Парцелляция и ударная концовка' '[.!?…] [А-ЯЁ][а-яё-]*( [а-яё-]+){0,2}[.!?]$'

  hit 'Многоточие — один знак' '\.\.\.'
  hit 'Кавычки ёлочками, внутри лапками' '"[^"]*"'
  hit 'Тире пишется «—» с пробелами, диапазон «–» без пробелов' ' [-–] |[0-9]-[0-9]'
  hit 'Наращение падежного окончания' '[0-9]+-(ми|та|тил)'
  hit 'Графическое сокращение пишется по норме' 'стр\. ?[0-9]'
  hit 'Дата пишется одним форматом' '[0-9]{2,4}-х гг\.'
  hit 'Диапазон пишется одним способом' '№ ?[0-9]+, ?№'
  hit 'Разряды отделяются узким неразрывным пробелом' '[0-9]{4,}.?(₽|€|%|руб|тыс|млн)'
  hit 'Знаки и единицы отбиваются по норме' '[0-9] ?[хx] ?[0-9]'
  hit 'Символ вместо слова' '→|≈|⚠|─'

  rm -f "$T"
done
